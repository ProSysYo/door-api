/**
 * Генератор serialNumber для заказов.
 *
 * Секунды от эпохи 2025-01-01: сейчас ~60 млн, через 8 лет ~315 млн.
 * При трафике в пару заказов в час попадание двух create в одну секунду
 * практически исключено. Если заказы пойдут потоком — заменить стратегию
 * здесь, в одном месте.
 */

const EPOCH = new Date('2025-01-01T00:00:00.000Z').getTime();

export function generateSerialNumber(): string {
  return `ORD-${Math.floor((Date.now() - EPOCH) / 1000)}`;
}
